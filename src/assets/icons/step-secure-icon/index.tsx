import { AnalysisStatus, AnalysisStep } from '@/features/health-record/helpers';

interface Props {
  step: AnalysisStep;
  status: AnalysisStatus;
  progress: number;
}

export function StepSecureIcon({ step, status, progress }: Props) {
  if (
    (step === AnalysisStep.SecureData || step === AnalysisStep.Validation) &&
    status === AnalysisStatus.Fail
  ) {
    return <StepSecureFail />;
  }

  if (progress > 25) {
    return <StepSecureDone />;
  }

  if (progress >= 25) {
    return <StepSecureProcessing />;
  }

  return <StepSecureNotStart />;
}

