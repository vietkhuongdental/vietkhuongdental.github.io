import { AnalysisStatus, AnalysisStep } from '@/features/health-record/helpers';

interface Props {
  status: AnalysisStatus;
  step: AnalysisStep;
  progress: number;
}

export function StepEncryptIcon({ status, progress, step }: Props) {
  if (
    (step === AnalysisStep.Encrypt || step === AnalysisStep.Preprocess) &&
    status === AnalysisStatus.Fail
  ) {
    return <StepEncryptFail />;
  }

  if (progress > 50) {
    return <StepEncryptDone />;
  }

  if (progress === 50) {
    return <StepEncryptProcessing />;
  }

  return <StepEncryptNotStart />;
}

