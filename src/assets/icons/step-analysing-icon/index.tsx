import { AnalysisStatus, AnalysisStep } from '@/features/health-record/helpers';

interface Props {
  status: AnalysisStatus;
  progress: number;
  step: AnalysisStep;
}

export function StepAnalysingIcon({ status, step, progress }: Props) {
  if (step === AnalysisStep.Analyze && status === AnalysisStatus.Fail) {
    return <StepAnalysingFail />;
  }

  if (progress > 75) {
    return <StepAnalysingDone />;
  }

  if (progress >= 75) {
    return <StepAnalysingProcessing />;
  }

  return <StepAnalysingNotStart />;
}

